import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const event=()=>({listeners:[],addListener(fn){this.listeners.push(fn)},emit(value){for(const fn of this.listeners)fn(value)}});
const port=()=>({onMessage:event(),onDisconnect:event(),sent:[],postMessage(value){this.sent.push(value)},disconnect(){this.closed=true;this.onDisconnect.emit()}});
const intervals=new Map();let next=0,opened=0;const native=port(),onConnect=event();
const chrome={action:{onClicked:event()},tabs:{create(){}},runtime:{onConnect,connectNative(){opened++;return native},getURL:p=>'chrome-extension://test/'+p,lastError:null}};
vm.runInNewContext(readFileSync('background.js','utf8'),{chrome,setInterval(fn){intervals.set(++next,fn);return next},clearInterval(id){intervals.delete(id)}});
const dashboard=port();dashboard.name='patreon-native';onConnect.emit(dashboard);
assert.equal(opened,1,'native connection must be owned by the background worker');
assert.equal(intervals.size,1,'worker schedules polling independently of dashboard timers');
for(let i=0;i<40;i++)for(const fn of intervals.values())fn();
assert.equal(dashboard.sent.filter(m=>m.bridge_tick).length,40,'idle dashboard receives polling events without running its own timer');
dashboard.onMessage.emit({action:'finish',request_id:'1'});
assert.equal(native.sent[0].action,'finish');
native.onMessage.emit({request_id:'1',result:{status:'complete'}});
assert.equal(dashboard.sent.at(-1).result.status,'complete');
assert.equal(intervals.size,1,'completion leaves polling running for the next job');
dashboard.onDisconnect.emit();assert(native.closed);assert.equal(intervals.size,0,'closing dashboard releases host and scheduler');
console.log('Background-owned native connection, hidden-dashboard scheduler, forwarding, and cleanup passed');
